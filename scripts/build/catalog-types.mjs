#!/usr/bin/env node
/* Audited JS remains the maintenance input. This deterministic compiler creates the browser's typed catalog. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { assertPublicSource } from "./vite-assets.mjs";

export const CATALOG_FILE = "src/generated/catalog.ts";
export const CATALOG_INPUTS = ["data/sources/data.js", "data/generated/benchmark-summary.js", "data/generated/maintenance-summary.js", "data/sources/project-data.js"];
const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed });
function typeNode(text) {
  const source = ts.createSourceFile("catalog-type.ts", `type CatalogType = ${text};`, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  /* 解析出的节点带着这段临时文本的位置；标为合成节点，打印时才不会按目标文件的同一位置取字面量。 */
  const synthesize = (node) => { ts.setTextRange(node, { pos: -1, end: -1 }); ts.forEachChild(node, synthesize); };
  const type = /** @type {import("typescript").TypeAliasDeclaration} */ (source.statements[0]).type;
  synthesize(type);
  return type;
}
/** 数据文件里的 JSDoc 类型（结构类型见 types/catalog.d.ts）原样转成 TypeScript 注解。 */
function jsDocType(node, source) {
  const type = ts.getJSDocType(node);
  return type ? typeNode(type.getText(source)) : undefined;
}
function collectBindingNames(name, out) {
  if (ts.isIdentifier(name)) out.push(name.text);
  else for (const element of name.elements) if (ts.isBindingElement(element)) collectBindingNames(element.name, out);
}

/** @param {string} root @returns {string} */
export function catalogSource(root) {
  const exports = [], seen = new Set(), parts = [];
  for (const file of CATALOG_INPUTS) {
    const input = path.join(root, file);
    assertPublicSource(root, input);
    const source = ts.createSourceFile(file, fs.readFileSync(input, "utf8"), ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
    const diagnostics = /** @type {import("typescript").SourceFile & { parseDiagnostics: readonly import("typescript").Diagnostic[] }} */ (source).parseDiagnostics;
    if (diagnostics.length) throw new Error(`${file} 解析失败：${ts.flattenDiagnosticMessageText(diagnostics[0].messageText, " ")}`);
    const names = [];
    for (const node of source.statements) {
      if (ts.isVariableStatement(node)) for (const declaration of node.declarationList.declarations) collectBindingNames(declaration.name, names);
      else if ((ts.isFunctionDeclaration(node) || ts.isClassDeclaration(node)) && node.name) names.push(node.name.text);
    }
    for (const name of names) {
      if (seen.has(name)) throw new Error(`目录顶层名称 ${name} 重复声明：${file}`);
      seen.add(name);
      exports.push(name);
    }
    const result = ts.transform(source, [(context) => {
      const visit = (node) => {
        if (ts.isVariableDeclaration(node) && !node.type) {
          const type = jsDocType(node, source);
          if (type) return ts.factory.updateVariableDeclaration(node, node.name, node.exclamationToken, type, /** @type {import("typescript").Expression | undefined} */ (ts.visitNode(node.initializer, visit)));
        }
        if (ts.isParameter(node) && !node.type) {
          const type = jsDocType(node, source);
          if (type) {
            /* JSDoc 的 [name] 表示可省略；带默认值的参数本身就可省略。 */
            const optional = !node.initializer && !node.questionToken && ts.getJSDocParameterTags(node).some((tag) => tag.isBracketed);
            return ts.factory.updateParameterDeclaration(node, node.modifiers, node.dotDotDotToken, node.name, optional ? ts.factory.createToken(ts.SyntaxKind.QuestionToken) : node.questionToken, type, node.initializer);
          }
          /* 回调参数由调用处推断类型；顶层函数的参数必须在数据文件里写明。 */
          if (ts.isFunctionDeclaration(node.parent)) {
            const { line } = source.getLineAndCharacterOfPosition(node.getStart(source));
            throw new Error(`${file}:${line + 1} 函数 ${node.parent.name?.text} 的参数 ${node.name.getText(source)} 缺少 JSDoc 类型`);
          }
        }
        if (ts.isFunctionDeclaration(node) && !node.type) {
          const returns = ts.getJSDocReturnType(node);
          if (returns) {
            const visited = /** @type {import("typescript").FunctionDeclaration} */ (ts.visitEachChild(node, visit, context));
            return ts.factory.updateFunctionDeclaration(visited, visited.modifiers, visited.asteriskToken, visited.name, visited.typeParameters, visited.parameters, typeNode(returns.getText(source)), visited.body);
          }
        }
        return ts.visitEachChild(node, visit, context);
      };
      return (fileNode) => /** @type {import("typescript").SourceFile} */ (ts.visitNode(fileNode, visit));
    }]);
    try { parts.push(printer.printFile(/** @type {import("typescript").SourceFile} */ (result.transformed[0])).trimEnd()); }
    finally { result.dispose(); }
  }
  return `/* Generated by scripts/build/catalog-types.mjs from audited maintenance sources. Run npm run catalog:build after source changes. */\n${parts.join("\n\n")}\n\nexport { ${exports.join(", ")} };\n`;
}

/** @param {string} root @param {{ check?: boolean }} [options] */
export function writeCatalog(root, options = {}) {
  const file = path.join(root, CATALOG_FILE);
  if (fs.existsSync(file)) assertPublicSource(root, file);
  const next = catalogSource(root);
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (current === next) return { file, changed: false };
  if (options.check) throw new Error(`${CATALOG_FILE} 已过期，请运行 npm run catalog:build`);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, next);
  return { file, changed: true };
}

/** 开发入口由 predev 显式生成；后续只在已登记输入变化时更新，配置加载与 SSR 本身不写源码。 */
export function watchCatalog({ root }) {
  const inputs = new Set(CATALOG_INPUTS.map((file) => path.resolve(root, file)));
  return {
    name: "coding-plan:watch-catalog",
    apply: "serve",
    hotUpdate(context) {
      if (!inputs.has(path.resolve(context.file))) return;
      writeCatalog(root);
    },
  };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
  try {
    const result = writeCatalog(root, { check: process.argv.includes("--check") });
    console.log(`✅ ${CATALOG_FILE} ${result.changed ? "已更新" : "与审计输入一致"}`);
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
